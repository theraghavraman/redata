#!/usr/bin/env python3
"""Write benchmarks/RESULTS.md from the JSON files in benchmarks/results/.

The tables are generated, never typed, so a number in the document can always
be traced to a committed result file. ``--check`` exits 1 if RESULTS.md is out
of date, which the test suite uses.

    python benchmarks/summarize_results.py
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
RESULTS = HERE / "results"
OUTPUT = HERE / "RESULTS.md"


def load():
    engine, sync = [], []
    for path in sorted(RESULTS.glob("*.json")):
        data = json.loads(path.read_text(encoding="utf-8"))
        data["_file"] = path.name
        (sync if "sync benchmark" in data.get("benchmark_type", "") else engine).append(data)
    return engine, sync


def rows_label(n: int) -> str:
    return "{:,}".format(n)


def seconds(ms: float) -> str:
    return "%.2f s" % (ms / 1000)


def environment(d: dict) -> str:
    cpu = d.get("cpu_model") or "%s vCPU" % d["cpu_count"]
    if d.get("cpu_model"):
        cpu = "%s, %s cores" % (cpu, d["cpu_count"])
    if d.get("ram_gib"):
        cpu += ", %s GiB" % d["ram_gib"]
    return "%s; %s; Python %s; DuckDB %s" % (cpu, d["platform"].split("-with")[0], d["python_version"].split()[0],
                                             d["duckdb_version"])


def engine_table(results) -> list[str]:
    lines = ["| Rows | Columns | CSV size | Import + profile | SQL aggregate | Page of rows | Peak RSS | Runs | Commit | File |",
             "| ---: | ---: | ---: | ---: | ---: | ---: | ---: | --- | --- | --- |"]
    for d in sorted(results, key=lambda d: (d["rows"], d["columns"], d["_file"])):
        repeated = "import_and_profile_ms_median" in d
        load_ms = d["import_and_profile_ms_median"] if repeated else d["import_and_profile_ms"]
        rss = "%.0f MiB" % (d["peak_engine_rss_kib_sampled"] / 1024) if d.get("peak_engine_rss_kib_sampled") else "not sampled"
        lines.append("| %s | %d | %.0f MB | %s | %.1f ms | %.1f ms | %s | %s | `%s` | [%s](results/%s) |" % (
            rows_label(d["rows"]), d["columns"], d["dataset_bytes"] / 1e6, seconds(load_ms), d["sql_query_median_ms"],
            d["page_5_rows_ms"], rss, "median of %d" % d["import_repeats"] if repeated else "single run",
            d["source_commit"][:7], d["_file"], d["_file"]))
    return lines


def sync_table(results) -> list[str]:
    def cell(step: dict) -> str:
        rate = " (%s rows/s)" % rows_label(step["rows_per_second"]) if step["rows_read"] else ""
        return "%s rows in %.2f s%s" % (rows_label(step["rows_read"]), step["seconds"], rate)

    lines = ["| Source rows | Full load | Append: new rows only | Append: nothing new | Upsert: new + changed rows | Peak RSS | Commit | File |",
             "| ---: | --- | --- | --- | --- | ---: | --- | --- |"]
    for d in sorted(results, key=lambda d: (d["rows"], d["_file"])):
        lines.append("| %s | %s | %s | %.3f s | %s | %s | `%s` | [%s](results/%s) |" % (
            rows_label(d["rows"]), cell(d["full_first_load"]), cell(d["append_incremental"]),
            d["append_nothing_new"]["seconds"], cell(d["upsert_incremental"]),
            "%.0f MiB" % d["peak_rss_mib"] if d.get("peak_rss_mib") else "not measured",
            (d.get("source_commit") or "unknown")[:7], d["_file"], d["_file"]))
    return lines


def render() -> str:
    engine, sync = load()
    out = ["# Benchmark results", "",
           "Generated by `python benchmarks/summarize_results.py` from the JSON files in [results/](results/). "
           "Do not edit by hand.", "",
           "Every row is one recorded run on one machine. The numbers describe that machine and that data, "
           "not what ReData will do everywhere. Each result file records the commit, the software versions, the "
           "dataset checksum and the correctness checks that had to pass for the run to count.", ""]
    if sync:
        out += ["## Sync pipeline", "",
                "`run_sync_benchmark.py`: a 6-column table synced from a local SQLite file into DuckDB staging "
                "tables through the real pipeline. There is no network in this measurement, so for remote "
                "databases read the rows/second as an upper bound. Every run checks row counts and `sum(amount)` "
                "against the source, that append read only the new rows, and that upsert left one row per key.", ""]
        out += sync_table(sync) + [""]
        for env in sorted({environment(d) for d in sync}):
            out.append("- Environment: %s; DuckDB threads: %s" % (env, ", ".join(
                sorted({str(d["duckdb_threads"]) for d in sync if environment(d) == env}))))
        out.append("")
    if engine:
        out += ["## Local engine over HTTP", "",
                "`run_engine_smoke.py`: a generated CSV imported and profiled through the engine's HTTP API, then "
                "queried. \"Import + profile\" covers reading the CSV into DuckDB and computing the full column "
                "profile. \"SQL aggregate\" is the median of repeated `SELECT COUNT(*), SUM(value)` requests. Every "
                "run checks the row count, the column count and the sum against independently computed values.", ""]
        out += engine_table(engine) + [""]
        for env in sorted({environment(d) for d in engine}):
            out.append("- Environment: %s (GitHub-hosted runner); DuckDB threads: 2" % env)
        out += ["",
                "These runs used the previous `http.server` front end. They have not been repeated on the FastAPI "
                "server; the import and query work is the same DuckDB code either way."]
        out.append("")
    out += ["## What these results do not show", "",
            "- They are not a reproduction of the older timings quoted from the v0.1.0 README (a 1 crore row, "
            "723 MB file on a 2-core machine). That input and machine are not available.",
            "- Runs marked \"single run\" have no repeat, so they carry no estimate of run-to-run variation.",
            "- Browser-only mode is not measured here.",
            "- No remote database, S3 or REST source is measured.", ""]
    return "\n".join(out)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="exit 1 if RESULTS.md is not up to date")
    args = parser.parse_args()
    text = render()
    if args.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != text:
            sys.stderr.write("benchmarks/RESULTS.md is out of date. Run: python benchmarks/summarize_results.py\n")
            return 1
        return 0
    OUTPUT.write_text(text, encoding="utf-8")
    print("Wrote %s" % OUTPUT)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
